def phrase_for(profile: str, seed: int, profile_cycle: int) -> tuple[str, str]:
    phrases = INTENT_PHRASES[profile]
    profile_offset = tuple(INTENT_PHRASES).index(profile) * 3
    seed_offset = DEFAULT_SEED_OFFSETS.get(seed, 7 * seed)
    index = (seed_offset + profile_cycle + profile_offset) % len(phrases)
    return f"{profile}-{index:02d}", phrases[index]
